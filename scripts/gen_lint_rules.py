#!/usr/bin/env python3
"""Generate docs/lint-rules.rst from the LINT rule catalogue.

Run after any change to ``python/pssparser/lint/catalog.py``, to a bundled
lint rule, or to a built-in declarative rule (``rules/*.yaml``, compiled
into the core: build first).  ``tests/python/lint/test_lint_rules_doc.py``
fails when the committed file is stale.

Only the rules shipped with pssparser are documented: the bundled extension
is in-tree, so the output is the same on every machine.  Third-party rules are
documented by their own packages (see docs/checker_plugin_guide.rst).
"""
from __future__ import annotations

import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT / "python"))

import re  # noqa: E402

from pssparser.checkers import taxonomy  # noqa: E402
from pssparser.lint import ruleview  # noqa: E402
from pssparser.lint.catalog import ALL  # noqa: E402

OUTPUT_PATH = _ROOT / "docs" / "lint-rules.rst"

_FAMILY_TITLES = {
    "constraint": "Constraints",
    "activity": "Activities",
    "exec": "Exec blocks and functions",
    "decl": "Declarations",
    "import": "Imports and packages",
    "register": "Registers",
    "evolution": "Deprecated forms",
    "naming": "Naming",
    "metric": "Metrics",
}

_HEADER = """\
Lint Rule Reference
===================

Every ``LINT`` rule shipped with pssparser, generated from
``pssparser.lint.catalog`` and the built-in rule files (``rules/*.yaml``) by
``scripts/gen_lint_rules.py`` -- do not edit this file by hand, it will be
overwritten.  ``pssparser --explain <ID or
name>`` prints the same entry at the command line; :doc:`lint` explains
profiles, selection and configuration.

Each rule has a **tier**, which sets its default severity and the profiles
that enable it:

.. list-table::
   :header-rows: 1

   * - Tier
     - Default severity
     - Profiles
{tier_rows}

Every profile except ``none`` also includes the ``minimal`` rules: the
warnings pssparser reported before lint existed.

"""


def _tier_rows() -> str:
    rows = []
    for tier in taxonomy.LINT_TIERS:
        profiles = [p for p, tiers in taxonomy.PROFILE_TIERS.items() if tier in tiers]
        rows.append(
            f"   * - ``{tier}``\n"
            f"     - {taxonomy.TIER_SEVERITY[tier]}\n"
            f"     - {', '.join(f'``{p}``' for p in profiles) or '(none; select explicitly)'}"
        )
    return "\n".join(rows)


def _indent(text: str, n: int = 3) -> str:
    pad = " " * n
    return "\n".join(pad + line if line.strip() else "" for line in text.splitlines())


def builtin_rules():
    """The built-in declarative rules (``rules/*.yaml``), as ``MarkerDef``s,
    read from the core they are compiled into."""
    from pssparser.core import Factory
    engine = Factory.inst().mkLintEngine()
    engine.load_builtin_rules()
    return [md for md in ruleview.marker_defs(engine.rules()) if ruleview.is_builtin(md)]


_FENCE = re.compile(r"^```[ \t]*(\w*)[ \t]*\n(.*?)^```[ \t]*$", re.M | re.S)
_CODE_SPAN = re.compile(r"(?<!`)`([^`\n]+)`(?!`)")
_LINK = re.compile(r"\[([^\]\n]+)\]\(([^)\s]+)\)")


def md_to_rst(text: str) -> str:
    """A declarative rule's ``doc:`` (Markdown) as reStructuredText: fenced
    code blocks, code spans and links; paragraphs and lists are the same in
    both."""
    def fence(m):
        lang = m.group(1) or "pss"
        return f".. code-block:: {lang}\n\n{_indent(m.group(2).rstrip())}"
    parts = []
    last = 0
    for m in _FENCE.finditer(text):
        parts.append(_inline(text[last:m.start()]))
        parts.append(fence(m))
        last = m.end()
    parts.append(_inline(text[last:]))
    return "".join(parts).strip()


def _inline(text: str) -> str:
    text = _CODE_SPAN.sub(r"``\1``", text)
    return _LINK.sub(r"`\1 <\2>`_", text)


def _entry(md) -> str:
    title = f"{md.id}: ``{md.name}``" if md.name else md.id
    out = [f".. _{md.id.lower()}:\n\n{title}\n{'~' * len(title)}\n\n"]
    facts = [f"**Tier:** {md.tier}", f"**Default severity:** {md.severity}"]
    if md.since:
        facts.append(f"**Since:** {md.since}")
    if md.aliases:
        facts.append("**Formerly:** " + ", ".join(f"``{a}``" for a in md.aliases))
    if md.fix != "none":
        facts.append(f"**Fix:** {md.fix}")
    if md.lrm:
        facts.append("**LRM:** " + ", ".join(md.lrm))
    if md.source:
        # A declarative rule: where it lives, and what the loader computed.
        facts.append(f"**Level:** {md.level}, {md.scope}")
        facts.append(f"**Defined in:** ``{md.source.rsplit(':', 2)[0].split(':', 1)[-1]}``")
    out.append("; ".join(facts) + "\n\n")
    out.append(f"{md.summary}\n\n")
    if md.detail:
        detail = md_to_rst(md.detail) if md.source else md.detail
        out.append(f"{detail}\n\n")
    for ex in md.examples:
        label = "Flagged" if ex.expect else "Not flagged"
        if ex.note:
            label += f" ({ex.note})"
        out.append(f"{label}:\n\n.. code-block:: pss\n\n{_indent(ex.code)}\n\n")
        if ex.fixed:
            out.append(f"After the fix:\n\n.. code-block:: pss\n\n{_indent(ex.fixed)}\n\n")
    return "".join(out)


def render(declarative=None) -> str:
    """The page, from the catalogue and *declarative* (the built-in rule
    files' rules; read from the core when ``None``)."""
    if declarative is None:
        declarative = builtin_rules()
    parts = [_HEADER.format(tier_rows=_tier_rows())]
    rules = sorted((md for md in list(ALL) + list(declarative) if md.emittable),
                   key=lambda m: m.id)
    for family in taxonomy.FAMILIES:
        members = [md for md in rules if md.family == family]
        if not members:
            continue
        title = _FAMILY_TITLES.get(family, family)
        parts.append(f"{title}\n{'-' * len(title)}\n\n")
        parts.extend(_entry(md) for md in members)
    return "".join(parts)


def main() -> int:
    OUTPUT_PATH.write_text(render())
    print(f"wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
