#!/usr/bin/env python3
"""Generate docs/lint-functions.rst from the lint engine's function registry.

The registry is C++ (src/lint/cel/CelStdLib.cpp, and the PSS library as it
is added); this script reads it through the built module, so build first.
Run after any change to a registered function.
``tests/python/lintcore/test_lint_functions_doc.py`` fails when the committed
file is stale.

Overloads outside the pss-rules profile (CEL features that the evaluator
accepts only for the conformance suite) are left out.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT / "python"))

OUTPUT_PATH = _ROOT / "docs" / "lint-functions.rst"

_HEADER = """\
Lint Rule Function Reference
============================

Every operator, function and macro a declarative lint rule's expressions can
use, generated from the lint engine's function registry by
``scripts/gen_lint_functions.py`` -- do not edit this file by hand, it will be
overwritten.

.. note::

   pssparser loads and checks declarative (``pss-rules``) rule files
   (:doc:`lint-rule-authoring`), but does not run them over a model yet.
   This reference is generated from the engine as it is built, ahead of the
   lint runner.

Rule expressions are written in a subset of `CEL
<https://github.com/google/cel-spec>`_, the Common Expression Language. The
functions below behave as the CEL specification defines them, and as cel-go
does where the specification leaves a detail open. Types are written as in
CEL: ``list(A)`` is a list whose elements have type ``A``, ``A`` and ``B`` are
type parameters, and ``node`` is any PSS syntax-tree node.

Each entry gives:

* **Level** -- what analysis the function needs: ``L0`` syntax only, ``L1``
  symbol resolution, ``L2`` types, ``L3`` constant values, ``L4`` the whole
  model. A rule's level is the highest level of the functions it calls.
* **Scope** -- ``file`` or ``model``. A rule that calls a ``model`` function
  is re-run on any change to the model; others only when their file changes.
* **Cost** -- what a call adds to the rule's evaluation budget, beyond one
  step per expression evaluated: ``constant``; ``linear``, one step per list
  or map element and per 64 string bytes in the operands; or ``custom``, as
  the description says.

"""


def _registry():
    from pssparser.core import Factory
    return Factory.inst()._lintTestHooks().cel_functions()["functions"]


def _title(fn: str) -> str:
    """How a function is named in its section title: the operator itself."""
    if fn == "@in":
        return "in"
    if fn == "_[_]":
        return "[]"
    if fn == "_[?_]":
        return "[?]"
    if fn == "_?_:_":
        return "? :"
    if fn == "_?._":
        return ".?"
    if len(fn) > 2 and fn[0] == "_" and fn[-1] == "_":
        return fn[1:-1]
    if len(fn) == 2 and fn[1] == "_":
        return fn[0] + " (unary)"
    return fn


def _rst(doc: str) -> str:
    # The registry's docs mark code with single backquotes, as Markdown does.
    return re.sub(r"`([^`]+)`", r"``\1``", doc)


def _section(overloads) -> str:
    first = overloads[0]
    title = f"``{_title(first['function'])}``"
    out = [f".. _lint-fn-{first['id'].replace('_', '-').lower()}:\n\n"
           f"{title}\n{'~' * len(title)}\n\n"]
    levels = sorted({(f["level"], f["scope"]) for f in overloads})
    out.append("; ".join(f"**Level:** {lv}; **Scope:** {sc}" for lv, sc in levels)
               + ("; **Macro**" if first["kind"] == "macro" else "") + "\n\n")

    if first["kind"] != "macro":
        out.append(".. list-table::\n   :header-rows: 1\n\n"
                   "   * - Signature\n     - Cost\n     - Overload\n")
        for f in overloads:
            out.append(f"   * - ``{f['display']}``\n     - {f['cost']}\n"
                       f"     - ``{f['id']}``\n")
        out.append("\n")
    else:
        for f in overloads:
            out.append(f"``{f['display']}``\n\n")

    docs = []
    for f in overloads:
        if f["doc"] not in [d for _, d in docs]:
            docs.append((f, f["doc"]))
    if len(docs) == 1:
        out.append(_rst(docs[0][1]) + "\n\n")
    else:
        # Different overloads say different things: each under its signature.
        for f, doc in docs:
            sigs = [g["display"] for g in overloads if g["doc"] == doc]
            out.append(", ".join(f"``{x}``" for x in sigs) + "\n   " + _rst(doc) + "\n\n")
    return "".join(out)


def render(functions=None) -> str:
    if functions is None:
        functions = _registry()
    functions = [f for f in functions if f["in_profile"]]
    parts = [_HEADER]
    groups = []
    for f in functions:
        if f["group"] not in groups:
            groups.append(f["group"])
    for g in groups:
        parts.append(f"{g}\n{'-' * len(g)}\n\n")
        names = []
        for f in functions:
            if f["group"] == g and f["function"] not in names:
                names.append(f["function"])
        for n in names:
            parts.append(_section([f for f in functions if f["group"] == g and f["function"] == n]))
    return "".join(parts).rstrip("\n") + "\n"


def main() -> int:
    OUTPUT_PATH.write_text(render())
    print(f"wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
