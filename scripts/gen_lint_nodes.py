#!/usr/bin/env python3
"""Generate docs/lint-nodes.rst: the syntax-tree classes a lint rule reads.

For each class: its base, its subclasses, what it is, and its own fields as a
rule's expression sees them (``node.attr``, ``node.super_t``), with the CEL
type the rule checker gives each.  The classes, fields and enums come from the
lint engine's reflection tables and the types from its checker, through the
built module, so build first; the descriptions and examples come from the
``doc:`` text of ``ast/*.yaml``.  Run after any change to ``ast/*.yaml`` or to
how the checker types a field.  ``tests/python/lintcore/test_lint_nodes_doc.py``
fails when the committed file is stale.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT / "python"))

OUTPUT_PATH = _ROOT / "docs" / "lint-nodes.rst"
AST_DIR = _ROOT / "ast"

_HEADER = """\
Lint Rule Node Reference
========================

The syntax-tree classes a declarative lint rule reads, generated from the
lint engine's reflection tables and ``ast/*.yaml`` by
``scripts/gen_lint_nodes.py`` -- do not edit this file by hand, it will be
overwritten.

A class name is a node kind: ``match: { kind: Field }`` matches it,
``n.isa(Field)`` and ``type(n) == Field`` test for it, and a subclass
matches wherever its base does. A rule reads a node's fields by name,
``node.name.id``, including the fields its bases declare: a ``Field`` has
``name`` from ``NamedScopeChild`` and ``location`` from ``ScopeChild``. An
unset node field is ``null``, an unset list is empty; test with ``has()`` or
read it with ``.?`` (see :doc:`lint-rule-authoring`). The functions that
move around the tree and read the linked model are in :doc:`lint-functions`.

The types are as the rule checker gives them. An enum field is an ``int``
compared against its constants (``node.op == ExprBinOp.BinOp_Eq``); a flags
field is a set of flags, tested with ``has_flag`` (see `Enums`_). Fields of
the linker's own classes that a rule cannot read are left out.

"""

# The ast/*.yaml files in the order their sections appear, with a heading.
_GROUPS = [
    ("coretypes", "Scopes and core classes"),
    ("typescope", "Type declarations"),
    ("struct", "Structs and objects"),
    ("field", "Fields"),
    ("datatype", "Data types"),
    ("template", "Templates"),
    ("template_types", "Template parameters"),
    ("expr", "Expressions"),
    ("constraint", "Constraints"),
    ("activity", "Activities"),
    ("exec", "Exec blocks and procedural statements"),
    ("functions", "Functions"),
    ("coverage", "Coverage"),
    ("monitor", "Monitors"),
    ("extension", "Extensions"),
    ("override", "Overrides"),
    ("annotation", "Annotations"),
    ("linking", "Linker classes"),
]

_LINKING_NOTE = (
    "The linker builds these alongside the tree; they are not written in "
    "the source, and a rule meets them only through a field that names one.")


def _schema():
    from pssparser.core import Factory
    return Factory.inst()._lintTestHooks().reflect_schema()


def _field_types(schema):
    """{(class, field): CEL type} from the checker, None where unreadable."""
    from pssparser.core import Factory
    from pssparser.parser import Parser
    hooks = Factory.inst()._lintTestHooks()
    p = Parser()
    p.parses([("probe.pss", "component pss_top { }\n")])
    root = p.link()
    (unit,) = p.user_units()
    out = {}
    for c in schema["classes"][1:]:
        for f in c["fields"]:
            expr = "descendants(node).filter(d, type(d) == %s).map(d, d.%s)" % (
                c["name"], f["name"])
            r = hooks.cel_check_node({"expr": expr}, unit, model=root)
            t = None
            if not r["errors"]:
                t = r["types"]["expr"]
                assert t.startswith("list(") and t.endswith(")"), t
                t = t[len("list("):-1]
            out[(c["name"], f["name"])] = t
    return out


def _items(node):
    """A class body, written as a mapping or as a list of one-key mappings."""
    if isinstance(node, dict):
        return node
    out = {}
    for e in node or []:
        if isinstance(e, dict):
            out.update(e)
    return out


def _ast_docs():
    """{class: (group, doc text)} and {enum value: comment} from ast/*.yaml."""
    classes, values = {}, {}
    for group, _ in _GROUPS:
        path = AST_DIR / (group + ".yaml")
        text = path.read_text()
        for m in re.finditer(r"^\s*- (\w+)\s*#\s*(.*?)\s*$", text, re.M):
            values.setdefault(m.group(1), m.group(2))
        doc = yaml.safe_load(text) or {}
        for entry in doc.get("classes") or []:
            for name, body in entry.items():
                classes[name] = (group, _items(body).get("doc") or "")
    return classes, values


def _parse_doc(doc):
    """(body, {attribute: description}) from a class's ``doc:`` text.

    The body is a list of ("p", paragraph) and ("code", block) items, in
    order: a line ending in ``::`` (``PSS Example::``) introduces an indented
    block. Attributes, See Also and Notes sections are taken out.
    """
    lines = doc.rstrip().splitlines()
    body, attrs, para = [], {}, []

    def flush():
        if para:
            body.append(("p", " ".join(l.strip() for l in para)))
            para.clear()

    def indented(i):
        block = []
        while i < len(lines) and (not lines[i].strip() or lines[i].startswith("    ")):
            block.append(lines[i][4:] if lines[i].startswith("    ") else "")
            i += 1
        while block and not block[0].strip():
            block.pop(0)
        while block and not block[-1].strip():
            block.pop()
        return block, i

    i = 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if s in ("Attributes:", "Fields:"):
            flush()
            block, i = indented(i + 1)
            key = None
            for l in block:
                m = re.match(r"(\w+)\s*:\s*(.*)$", l)
                if m and not l.startswith(" "):
                    key = m.group(1)
                    attrs[key] = m.group(2).strip()
                elif key and l.strip():
                    attrs[key] += " " + l.strip()
            continue
        if s.endswith(":") and s[:-1] in ("See Also", "Note", "Notes", "Usage"):
            flush()
            _, i = indented(i + 1)
            continue
        if s.endswith("::") and i + 2 < len(lines) and not lines[i + 1].strip() \
                and lines[i + 2].startswith("    "):
            head = s[:-2].rstrip()
            if head and head not in ("PSS Example", "Example", "Examples", "PSS Examples"):
                para.append(head + ":")
            flush()
            block, i = indented(i + 1)
            if block:
                body.append(("code", "\n".join(block)))
            continue
        if not s:
            flush()
        else:
            para.append(line)
        i += 1
    flush()
    return body, attrs


def _rst_text(s):
    # The ast docs use `x` for code; reStructuredText wants ``x``. Outside
    # literals, '*', '|' and an unmatched '`' are markup, so escape them.
    s = re.sub(r"(?<!`)`([^`\n]+)`(?!`)", lambda m: "``%s``" % m.group(1).strip(), s)
    parts = re.split(r"(``.+?``)", s)
    return "".join(p if p.startswith("``") else re.sub(r"(?<!`)`(?!`)", r"\\`", re.sub(r"([*|])", r"\\\1", p))
                   for p in parts)


def _type_rst(t, class_names, field=None, enums=None):
    if t is None:
        return "--"
    if field and field["type"] in ("enum", "flags"):
        e = enums[field["target"]]["name"]
        return "``%s`` %s (see :ref:`lint-enum-%s`)" % (
            e, "flags" if field["type"] == "flags" else "enum", e)
    m = re.fullmatch(r"list\((\w+)\)", t)
    if m and m.group(1) in class_names:
        return "list of :ref:`%s <lint-node-%s>`" % (m.group(1), m.group(1))
    if t in class_names:
        return ":ref:`%s <lint-node-%s>`" % (t, t)
    return "``%s``" % t


def render(schema=None, types=None) -> str:
    if schema is None:
        schema = _schema()
    if types is None:
        types = _field_types(schema)
    docs, values = _ast_docs()
    classes = schema["classes"]
    names = {c["name"] for c in classes[1:]}
    subs = {}
    for c in classes[1:]:
        if c["super"]:
            subs.setdefault(classes[c["super"]]["name"], []).append(c["name"])

    out = [_HEADER]
    by_group = {}
    for c in classes[1:]:
        group = docs.get(c["name"], ("linking", ""))[0]
        by_group.setdefault(group, []).append(c)

    for group, title in _GROUPS:
        members = sorted(by_group.get(group, []), key=lambda c: c["name"])
        if not members:
            continue
        out.append("%s\n%s\n\n" % (title, "-" * len(title)))
        if group == "linking":
            out.append(_LINKING_NOTE + "\n\n")
        for c in members:
            name = c["name"]
            out.append(".. _lint-node-%s:\n\n``%s``\n%s\n\n" % (name, name, "~" * (len(name) + 4)))
            body, attrs = _parse_doc(docs.get(name, ("", ""))[1])
            facts = []
            if c["super"]:
                b = classes[c["super"]]["name"]
                facts.append("Base: :ref:`%s <lint-node-%s>`." % (b, b))
            if name in subs:
                facts.append("Subclasses: %s." % ", ".join(
                    ":ref:`%s <lint-node-%s>`" % (s, s) for s in sorted(subs[name])))
            if facts:
                out.append(" ".join(facts) + "\n\n")
            for kind, text in body:
                if kind == "p":
                    out.append(_rst_text(text) + "\n\n")
                else:
                    # No Pygments lexer for PSS is installed with the docs.
                    out.append(".. code-block:: none\n\n")
                    out.append("\n".join(("   " + l) if l.strip() else ""
                                         for l in text.splitlines()))
                    out.append("\n\n")
            fields = [f for f in c["fields"] if types.get((name, f["name"]))]
            if fields:
                out.append(".. list-table::\n   :header-rows: 1\n   :widths: 20 25 55\n\n")
                out.append("   * - Field\n     - Type\n     - Description\n")
                for f in fields:
                    out.append("   * - ``%s``\n     - %s\n     - %s\n" % (
                        f["name"], _type_rst(types[(name, f["name"])], names, f, schema["enums"]),
                        _rst_text(attrs.get(f["name"], ""))))
                out.append("\n")

    out.append("Enums\n-----\n\n")
    out.append(
        "A rule names an enum constant as ``Enum.Value``. A flags enum's field "
        "holds a set of them: test one with ``has_flag(node.attr, "
        "FieldAttr.Rand)``; it is not a number. A plain enum's field holds one, "
        "compared with ``==``.\n\n")
    for e in sorted(schema["enums"], key=lambda e: e["name"]):
        title = "``%s``" % e["name"]
        out.append(".. _lint-enum-%s:\n\n%s\n%s\n\n" % (e["name"], title, "~" * len(title)))
        out.append("%s.\n\n" % ("Flags" if e["flags"] else "Enum"))
        for v in e["values"]:
            comment = values.get(v, "")
            out.append("* ``%s.%s``%s\n" % (
                e["name"], v, (" -- " + _rst_text(comment)) if comment else ""))
        out.append("\n")

    out.append("Structs\n-------\n\n")
    out.append("Values a node field holds that are not nodes, read by member "
               "(``node.location.lineno``).\n\n")
    for s in sorted(schema["structs"], key=lambda s: s["name"]):
        title = "``%s``" % s["name"]
        out.append("%s\n%s\n\n" % (title, "~" * len(title)))
        out.append(", ".join("``%s``" % f["name"] for f in s["fields"]) + ".\n\n")
    return "".join(out).rstrip() + "\n"


def main() -> int:
    OUTPUT_PATH.write_text(render())
    print(f"wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
