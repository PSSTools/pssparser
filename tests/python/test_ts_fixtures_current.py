"""The TypeScript parity fixtures match the parser under test (known-issues TS-1).

``ts/test/fixtures/*-parity.json`` are what the native parser reports, and the
TypeScript tests check the WebAssembly build against them. Nothing used to
check the fixtures against the native parser: they went three weeks stale,
and a stale fixture hid one real WASM bug (marker columns one character late)
among 246 failures nobody saw, because CI did not run the TypeScript tests.

Each fixture is regenerated here, out of process, by the script that wrote
it, and must come out byte-for-byte identical. A failure means a change to
the parser or to a generator was made without regenerating: run the
``npm run gen:*-fixture`` script the message names (``ts/README.md``),
then run the TypeScript tests (``cd ts && npm test``), since what changed on
the native side must also hold for the WebAssembly build.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from .isolation import _child_env

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "ts" / "scripts"
FIXTURES = ROOT / "ts" / "test" / "fixtures"
CORPUS = ROOT / "packages" / "pss-corpus" / "curated"

#: (fixture name, reads the corpus)
FIXTURE_SPECS = [
    ("parity", True),
    ("ast-parity", True),
    ("link-parity", True),
    ("census-parity", True),
    ("lintcore-parity", False),
]


def _run(args, cwd):
    r = subprocess.run([sys.executable] + args, cwd=cwd, env=_child_env(),
                       capture_output=True, text=True)
    assert r.returncode == 0, (
        "%s failed (%d):\n%s%s" % (args[0], r.returncode, r.stdout, r.stderr))


@pytest.fixture(scope="module")
def census_dir(tmp_path_factory):
    """A census walker generated now, from this checkout's schema.

    Not ts/scripts/generated: that one is written by `npm run gen:census` and
    may predate the schema the parser was built from.
    """
    pytest.importorskip("astbuilder", reason="the census walker is generated by pyastbuilder")
    out = tmp_path_factory.mktemp("census")
    _run(["-m", "astbuilder", "gen-census", "-astdir", str(ROOT / "ast"),
          "-py", str(out), "-ts", str(out)], cwd=ROOT)
    return out


def _case_diff(want, got):
    """The ids of the cases that differ, so the message says where to look."""
    a = {c.get("id"): c for c in want.get("cases", [])}
    b = {c.get("id"): c for c in got.get("cases", [])}
    ids = [i for i in a if i not in b or a[i] != b[i]]
    ids += [i for i in b if i not in a]
    return ids


@pytest.mark.parametrize("name,uses_corpus", FIXTURE_SPECS,
                         ids=[n for n, _ in FIXTURE_SPECS])
def test_fixture_is_current(name, uses_corpus, tmp_path, request):
    if uses_corpus and not CORPUS.is_dir():
        pytest.skip("no corpus at %s (ivpm update)" % CORPUS)
    out = tmp_path / (name + ".json")
    args = [str(SCRIPTS / ("gen-%s-fixture.py" % name)), "-o", str(out)]
    if name == "census-parity":
        args += ["--census-dir", str(request.getfixturevalue("census_dir"))]
    _run(args, cwd=ROOT)

    committed = FIXTURES / (name + ".json")
    if out.read_bytes() == committed.read_bytes():
        return
    differ = _case_diff(json.loads(committed.read_text()), json.loads(out.read_text()))
    shown = ", ".join(str(i) for i in differ[:10])
    more = " and %d more" % (len(differ) - 10) if len(differ) > 10 else ""
    pytest.fail(
        "ts/test/fixtures/%s.json is stale (cases: %s%s) -- run "
        "`npm run gen:%s-fixture` in ts/, then `npm test` there, and commit "
        "the fixture" % (name, shown or "none; the header differs", more, name))
