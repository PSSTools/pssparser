#!/usr/bin/env python3
"""Embed the built-in rule files (``rules/*.yaml``) in the core.

lint-core-plan.md C4.3; pss-rules-format.md §6.2.  Writes a C++ source that
defines ``pssp::lint::rules::builtinRuleFiles()`` (declared in
``BuiltinRules.h``): each file's name and bytes, in name order.  The bytes
are written as a char array rather than a string literal, so there is no
length limit (MSVC caps a literal at 16 KB) and no delimiter to escape.

Usage: mk_builtin_rules.py RULES_DIR OUT.cpp

Standalone on purpose, like mk_pssstdlib.py: both the native and the WASM
build run it.  The output is written only when it changes, so a re-run does
not force a rebuild.
"""
import io
import os
import sys

HEADER = """\
/*
 * BuiltinRules.cpp -- GENERATED by src/lint/rules/mk_builtin_rules.py from
 * the files in rules/. Do not edit.
 *
 * Copyright 2026 Matthew Ballance and Contributors
 *
 * Licensed under the Apache License, Version 2.0 (the "License"); you may
 * not use this file except in compliance with the License.
 * You may obtain a copy of the License at:
 *
 *   http://www.apache.org/licenses/LICENSE-2.0
 *
 * Unless required by applicable law or agreed to in writing, software
 * distributed under the License is distributed on an "AS IS" BASIS,
 * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
 * See the License for the specific language governing permissions and
 * limitations under the License.
 */
#include "rules/BuiltinRules.h"

namespace pssp {
namespace lint {
namespace rules {

"""

FOOTER = """\
}
}
}
"""

#: The name a built-in file has in diagnostics: never a path on the user's
#: disk, since the file is inside the binary.
NAME_PREFIX = "pssparser:rules/"

EXTENSIONS = (".yaml", ".yml")


def rule_files(rules_dir):
    """The built-in rule files, sorted: listdir order is filesystem-dependent,
    and the output must be the same on every machine."""
    if not os.path.isdir(rules_dir):
        return []
    return [f for f in sorted(os.listdir(rules_dir))
            if os.path.splitext(f)[1] in EXTENSIONS
            and os.path.isfile(os.path.join(rules_dir, f))]


def generate(rules_dir):
    out = io.StringIO()
    out.write(HEADER)
    files = rule_files(rules_dir)
    for i, f in enumerate(files):
        with open(os.path.join(rules_dir, f), "rb") as fp:
            data = fp.read()
        out.write("// %s\n" % f)
        out.write("static const char file_%d[] = {\n" % i)
        for at in range(0, len(data), 16):
            out.write("    " + "".join("%d," % b for b in data[at:at + 16]) + "\n")
        out.write("    0\n};\n\n")

    out.write("static const BuiltinRuleFile files[] = {\n")
    for i, f in enumerate(files):
        size = os.path.getsize(os.path.join(rules_dir, f))
        out.write('    {"%s%s", file_%d, %d},\n' % (NAME_PREFIX, f, i, size))
    # A zero-length array is not C++; the sentinel also makes the count
    # independent of sizeof.
    out.write("    {nullptr, nullptr, 0}\n};\n\n")

    out.write("const BuiltinRuleFile *builtinRuleFiles() {\n")
    out.write("    return files;\n}\n\n")
    out.write(FOOTER)
    return out.getvalue()


def write_if_changed(path, content):
    try:
        with open(path, "r") as fp:
            if fp.read() == content:
                return False
    except (FileNotFoundError, IsADirectoryError, UnicodeDecodeError):
        pass
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as fp:
        fp.write(content)
    return True


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: mk_builtin_rules.py RULES_DIR OUT.cpp\n")
        return 2
    content = generate(argv[1])
    if argv[2] == "-":
        sys.stdout.write(content)
    else:
        write_if_changed(argv[2], content)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
