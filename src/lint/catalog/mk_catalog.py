#!/usr/bin/env python3
"""Embed the marker catalogue (``catalog.json``) in the core.

lint-core-plan.md C7.3.  Writes a C++ source that defines
``pssp::lint::catalog::catalogText()`` (declared in ``Catalog.h``): the bytes
of ``catalog.json``, which ``scripts/gen_catalog.py`` generates from the
Python ``MarkerDef``s.  As in mk_builtin_rules.py, the bytes are a char array
rather than a string literal (no length limit, nothing to escape), unsigned
so UTF-8 bytes do not narrow, and the
output is written only when it changes.

Usage: mk_catalog.py CATALOG.json OUT.cpp
"""
